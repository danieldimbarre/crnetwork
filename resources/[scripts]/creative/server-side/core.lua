-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
local Tunnel = module("vrp","lib/Tunnel")
local Proxy = module("vrp","lib/Proxy")
vRP = Proxy.getInterface("vRP")
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
Creative = {}
Tunnel.bindInterface("creative",Creative)
-----------------------------------------------------------------------------------------------------------------------------------------
-- VARIABLES
-----------------------------------------------------------------------------------------------------------------------------------------
local Players = {}
-----------------------------------------------------------------------------------------------------------------------------------------
-- LIST
-----------------------------------------------------------------------------------------------------------------------------------------
local List = {
	[15] = {
		["Route"] = 1,
		["Other"] = vec3(848.79,3003.35,44.52)
	},
	[16] = {
		["Route"] = 0
	},
	[17] = {
		["Route"] = 1,
		["Other"] = vec3(-391.17,4354.86,57.68)
	},
	[18] = {
		["Route"] = 0
	}
}
-----------------------------------------------------------------------------------------------------------------------------------------
-- REQUESTPERM
-----------------------------------------------------------------------------------------------------------------------------------------
function Creative.requestPerm(Type)
	local source = source
	local Passport = vRP.Passport(source)
	if Passport then
		if Type ~= nil then
			if not vRP.HasGroup(Passport,Type) then
				return false
			end
		end

		return true
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- REQUESTPERM
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterServerEvent("creative:SyncBucket")
AddEventHandler("creative:SyncBucket",function(Index)
	local source = source

	if List[Index] then
		if Players[source] then
			Players[source] = nil
		end

		if List[Index]["Other"] then
			Players[source] = Index
		end

		Player(source)["state"]["Route"] = List[Index]["Route"]
		SetPlayerRoutingBucket(source,List[Index]["Route"])
	end
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- DISCONNECT
-----------------------------------------------------------------------------------------------------------------------------------------
AddEventHandler("Disconnect",function(Passport,source)
	if Players[source] then
		vRP.Teleport(source,List[Index]["Other"][Players[source]]["x"],List[Index]["Other"][Players[source]]["y"],List[Index]["Other"][Players[source]]["z"])

		Players[source] = nil
	end
end)