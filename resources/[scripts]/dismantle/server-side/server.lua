-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
local Tunnel = module('vrp','lib/Tunnel')
local Proxy = module('vrp','lib/Proxy')
local vRP = Proxy.getInterface('vRP')
-----------------------------------------------------------------------------------------------------------------------------------------
-- VARIABLES
-----------------------------------------------------------------------------------------------------------------------------------------
local dismantleCars = {}
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
local arc = {}
Tunnel.bindInterface('dismantle', arc)
local vCLIENT = Tunnel.getInterface('dismantle')
-----------------------------------------------------------------------------------------------------------------------------------------
-- PREPARES
-----------------------------------------------------------------------------------------------------------------------------------------
vRP.Prepare('arcade/setArrested', 'UPDATE vehicles SET arrest = 1 WHERE plate = @plate')
-----------------------------------------------------------------------------------------------------------------------------------------
-- CHECKPERM
-----------------------------------------------------------------------------------------------------------------------------------------
function arc.checkConditions(plate)
	local source = source
	local user_id = vRP.Passport(source)
	local vehOwner = vRP.PassportPlate(plate)
	
	if not vehOwner then
		return false
	end

	for _, permiss in pairs(config.permiss) do
		if vRP.HasPermission(user_id, permiss) and vRP.TakeItem(user_id, config.consumeItem[1], config.consumeItem[2], true) then
			vRP.Query('arcade/setArrested', { plate = plate })
			return true
		end
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- GIVEITEM
-----------------------------------------------------------------------------------------------------------------------------------------
function arc.giveItem(item)
	local source = source
	local user_id = vRP.Passport(source)

	for _, item in pairs(config.itens[item]) do
		vRP.GenerateItem(user_id, item[1], item[2], true)
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- BLOCKREAPIR
-----------------------------------------------------------------------------------------------------------------------------------------
function arc.blockRepair(netId)
	local vehicle = NetworkGetEntityFromNetworkId(netId)
	dismantleCars[vehicle] = true
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- EXPORTSNOREPAIR
-----------------------------------------------------------------------------------------------------------------------------------------
exports('vehicleCanBeRepaired', function(vehicle)
	return dismantleCars[vehicle] == true
end)