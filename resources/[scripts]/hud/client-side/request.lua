-----------------------------------------------------------------------------------------------------------------------------------------
-- VARIABLES
-----------------------------------------------------------------------------------------------------------------------------------------
local Active = false
local Results = false
-----------------------------------------------------------------------------------------------------------------------------------------
-- REQUESTSUCESS
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("RequestSucess",function()
	Results = true
	Active = false
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- REQUESTFAILURE
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNUICallback("RequestFailure",function()
	Results = false
	Active = false
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- REQUEST
-----------------------------------------------------------------------------------------------------------------------------------------
function Creative.Request(Message,Accept,Reject)
	if Active then
		return false
	end

	Active = true
	SendNUIMessage({ Action = "Request", Message = Message, Accept = Accept, Reject = Reject })

	while Active do
		Wait(0)
	end

	return Results
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- REQUESTY
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterCommand("RequestY",function()
	if Active then
		SendNUIMessage({ Action = "Y" })
	end
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- REQUESTU
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterCommand("RequestU",function()
	if Active then
		SendNUIMessage({ Action = "U" })
	end
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- KEYMAPPING
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterKeyMapping("RequestY","Aceitar requisições.","keyboard","Y")
RegisterKeyMapping("RequestU","Rejeitar requisições.","keyboard","U")