-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
local Tunnel = module("vrp","lib/Tunnel")
local Proxy = module("vrp","lib/Proxy")
vRP = Proxy.getInterface("vRP")
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
Creative = {}
Tunnel.bindInterface("taxi",Creative)
-----------------------------------------------------------------------------------------------------------------------------------------
-- PAYMENTSERVICE
-----------------------------------------------------------------------------------------------------------------------------------------
function Creative.paymentService()
	local source = source
	local Passport = vRP.Passport(source)
	if Passport then
		local value = math.random(175,275)
		vRP.GenerateItem(Passport,"dollars",value,true)
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- INITSERVICE
-----------------------------------------------------------------------------------------------------------------------------------------
function Creative.initService(status)
	local source = source
	local Passport = vRP.Passport(source)
	if Passport then
		if status then
			vRP.AddPermission(source,Passport,"Taxi")
		else
			vRP.RemovePermission(Passport,"Taxi")
		end
	end

	return true
end